#Requires -Version 5.1
<#
.SYNOPSIS
  Install Tavris1's ComfyUI-Easy-Install and configure a shared model folder.

.DESCRIPTION
  ComfyUI-Easy-Install has no silent mode, so this wrapper automates everything
  around it: it downloads the latest release, extracts it into a same-volume
  staging folder, starts the official interactive installer, waits for it, moves
  the finished install to a clean path, and points ComfyUI at the shared model
  store used by the Pixaroma setup scripts and Stable Diffusion WebUI.

  Run this from a NORMAL (non-administrator) terminal. The Easy-Install batch
  file deliberately refuses to run elevated.

.EXAMPLE
  Set-ExecutionPolicy -Scope Process Bypass
  .\install-comfyui-easy.ps1 -ParentDir C:\AI -ModelsRoot D:\AI\models

.NOTES
  Easy-Install is interactive: follow the prompts in its console window.
#>
[CmdletBinding()]
param(
    [string]$ParentDir,
    [string]$ModelsRoot,
    [switch]$DryRun,
    [switch]$SkipConfig
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
try { [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12 } catch { }

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$isWindowsHost = ($env:OS -eq 'Windows_NT')

function Write-Step([string]$Message) { Write-Host "`n== $Message ==" -ForegroundColor Cyan }
function Write-Info([string]$Message) { Write-Host "   $Message" }
function Write-Warn2([string]$Message) { Write-Host "   warning: $Message" -ForegroundColor Yellow }
function Fail([string]$Message) { throw $Message }

function Write-TextFile {
    param([string]$Path, [string]$Text)
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Force -Path $dir | Out-Null
    }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [IO.File]::WriteAllText($Path, $Text, $utf8)
}

function Format-Bytes([int64]$Bytes) {
    if ($Bytes -ge 1000000000000) { return ('{0:N2} TB' -f ($Bytes / 1e12)) }
    if ($Bytes -ge 1000000000) { return ('{0:N2} GB' -f ($Bytes / 1e9)) }
    if ($Bytes -ge 1000000) { return ('{0:N2} MB' -f ($Bytes / 1e6)) }
    if ($Bytes -ge 1000) { return ('{0:N1} KB' -f ($Bytes / 1e3)) }
    return "$Bytes B"
}

function Test-IsAdmin {
    try {
        $id = [Security.Principal.WindowsIdentity]::GetCurrent()
        $p = New-Object Security.Principal.WindowsPrincipal($id)
        return $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    } catch { return $false }
}

function Get-DefaultParentDir {
    if (-not $isWindowsHost) { return (Join-Path $HOME 'AI') }
    $systemDrive = $env:SystemDrive
    if (-not $systemDrive) { $systemDrive = 'C:' }
    return (Join-Path $systemDrive 'AI')
}

function Get-DefaultModelsRoot {
    if (-not $isWindowsHost) { return (Join-Path $HOME 'AI/models') }
    $drives = @()
    foreach ($d in Get-PSDrive -PSProvider FileSystem -ErrorAction SilentlyContinue) {
        if ($d.Name -match '^[A-Za-z]$' -and $null -ne $d.Free -and $d.Free -gt 0) {
            $drives += $d
        }
    }
    if (-not $drives -or $drives.Count -eq 0) {
        return (Join-Path $env:USERPROFILE 'AI\models')
    }
    $best = $drives | Sort-Object -Property Free -Descending | Select-Object -First 1
    return (Join-Path ($best.Name + ':') 'AI\models')
}

function Read-PixaromaConf {
    $conf = Join-Path $scriptDir 'pixaroma.conf'
    $values = @{}
    if (Test-Path -LiteralPath $conf) {
        foreach ($line in Get-Content -LiteralPath $conf) {
            if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$') {
                $values[$Matches[1]] = $Matches[2].Trim()
            }
        }
    }
    return $values
}

function Write-PixaromaConf {
    param([string]$ComfyDir, [string]$Root)
    $values = Read-PixaromaConf
    if ($ComfyDir) { $values['COMFYUI'] = $ComfyDir }
    if ($Root) { $values['MODELS_ROOT'] = $Root }
    $order = @('COMFYUI', 'MODELS_ROOT', 'SD_WEBUI')
    $lines = @('# Generated by the Pixaroma installers. Command-line flags override these values.')
    foreach ($k in $order) {
        if ($values.ContainsKey($k) -and $values[$k]) { $lines += "$k=$($values[$k])" }
    }
    foreach ($k in ($values.Keys | Sort-Object)) {
        if ($order -notcontains $k -and $values[$k]) { $lines += "$k=$($values[$k])" }
    }
    $conf = Join-Path $scriptDir 'pixaroma.conf'
    if ($DryRun) { Write-Info "[dry-run] write $conf"; return }
    try {
        Write-TextFile -Path $conf -Text (($lines -join "`r`n") + "`r`n")
        Write-Info "wrote $conf"
    } catch {
        Write-Warn2 "could not write ${conf}: $($_.Exception.Message)"
    }
}

function Initialize-SharedModels {
    param([string]$Root)
    $folders = @(
        'checkpoints', 'diffusion_models', 'text_encoders', 'clip', 'clip_vision',
        'vae', 'loras', 'embeddings', 'controlnet', 'upscale_models',
        'latent_upscale_models', 'model_patches', 'audio_encoders',
        'background_removal', 'detection', 'sam3', 'geometry_estimation',
        'SEEDVR2', 'style_models', 'gligen', 'photomaker', 'classifiers',
        'frame_interpolation', 'optical_flow', 'hypernetworks', 'configs',
        'diffusers', 'vae_approx'
    )
    foreach ($f in $folders) {
        $p = Join-Path $Root $f
        if ($DryRun) { Write-Info "[dry-run] mkdir $p" }
        elseif (-not (Test-Path -LiteralPath $p)) { New-Item -ItemType Directory -Force -Path $p | Out-Null }
    }
}

function Write-ExtraModelPaths {
    param([string]$ComfyRoot, [string]$Root)
    $yamlPath = Join-Path $ComfyRoot 'extra_model_paths.yaml'
    $base = ($Root -replace '\\', '/') -replace '"', '\"'
    $block = @"
pixaroma_shared:
    base_path: "$base"
    is_default: true
    checkpoints: checkpoints
    diffusion_models: diffusion_models
    text_encoders: text_encoders
    clip: text_encoders
    clip_vision: clip_vision
    vae: vae
    loras: loras
    embeddings: embeddings
    controlnet: controlnet
    upscale_models: upscale_models
    latent_upscale_models: latent_upscale_models
    model_patches: model_patches
    audio_encoders: audio_encoders
    background_removal: background_removal
    detection: detection
    sam3: sam3
    geometry_estimation: geometry_estimation
    SEEDVR2: SEEDVR2
    style_models: style_models
    gligen: gligen
    photomaker: photomaker
    classifiers: classifiers
    frame_interpolation: frame_interpolation
    optical_flow: optical_flow
    hypernetworks: hypernetworks
    configs: configs
    diffusers: diffusers
    vae_approx: vae_approx
"@
    if (-not (Test-Path -LiteralPath $yamlPath)) {
        if ($DryRun) { Write-Info "[dry-run] write $yamlPath"; return }
        Write-TextFile -Path $yamlPath -Text $block
        Write-Info "wrote $yamlPath"
        return
    }
    $existing = Get-Content -LiteralPath $yamlPath -Raw
    if ($existing -match '(?m)^pixaroma_shared:') {
        Write-Info "extra_model_paths.yaml already contains pixaroma_shared; left unchanged"
        return
    }
    if ($DryRun) { Write-Info "[dry-run] append pixaroma_shared to $yamlPath"; return }
    Add-Content -LiteralPath $yamlPath -Value "`r`n$block" -Encoding UTF8
    Write-Info "appended pixaroma_shared to $yamlPath"
}

function Expand-ZipSafe {
    param([string]$Zip, [string]$Dest)
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    if (-not (Test-Path -LiteralPath $Dest)) { New-Item -ItemType Directory -Force -Path $Dest | Out-Null }
    $rootFull = [IO.Path]::GetFullPath($Dest).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    $archive = [IO.Compression.ZipFile]::OpenRead($Zip)
    try {
        foreach ($entry in $archive.Entries) {
            if ([string]::IsNullOrEmpty($entry.Name)) { continue }
            $rel = $entry.FullName -replace '\\', '/'
            if ($rel.StartsWith('/') -or $rel -match '(^|/)\.\.(/|$)') { continue }
            $out = Join-Path $Dest $rel
            $full = [IO.Path]::GetFullPath($out)
            if (-not $full.StartsWith($rootFull, [StringComparison]::OrdinalIgnoreCase)) {
                Write-Warn2 "skipped unsafe zip entry: $rel"
                continue
            }
            $parent = Split-Path -Parent $full
            if (-not (Test-Path -LiteralPath $parent)) { New-Item -ItemType Directory -Force -Path $parent | Out-Null }
            [IO.Compression.ZipFileExtensions]::ExtractToFile($entry, $full, $true)
        }
    } finally {
        $archive.Dispose()
    }
}

function Download-File {
    param([string]$Url, [string]$Dest, [int64]$ExpectedSize = 0)
    if (Test-Path -LiteralPath $Dest) {
        $len = (Get-Item -LiteralPath $Dest).Length
        if ($ExpectedSize -le 0 -or $len -eq $ExpectedSize) {
            Write-Info "reusing downloaded file: $Dest"
            return
        }
        if (-not $DryRun) { Remove-Item -LiteralPath $Dest -Force }
    }
    if ($DryRun) { Write-Info "[dry-run] download $Url -> $Dest"; return }
    $parent = Split-Path -Parent $Dest
    if ($parent -and -not (Test-Path -LiteralPath $parent)) { New-Item -ItemType Directory -Force -Path $parent | Out-Null }
    $part = "$Dest.part"
    if (Test-Path -LiteralPath $part) { Remove-Item -LiteralPath $part -Force }
    $curl = Get-Command curl.exe -ErrorAction SilentlyContinue
    if (-not $curl) { $curl = Get-Command curl -ErrorAction SilentlyContinue }
    if ($curl) {
        & $curl.Source -L --fail --retry 5 --retry-delay 3 -o $part $Url
        if ($LASTEXITCODE -ne 0) {
            if (Test-Path -LiteralPath $part) { Remove-Item -LiteralPath $part -Force }
            Fail "download failed: $Url"
        }
    } else {
        Invoke-WebRequest -UseBasicParsing -Uri $Url -OutFile $part
    }
    if ($ExpectedSize -gt 0 -and (Get-Item -LiteralPath $part).Length -ne $ExpectedSize) {
        Remove-Item -LiteralPath $part -Force
        Fail "downloaded size does not match the release asset size"
    }
    Move-Item -LiteralPath $part -Destination $Dest -Force
}

# --------------------------------------------------------------------- defaults
if (-not $isWindowsHost -and -not $DryRun) {
    Fail "ComfyUI-Easy-Install is Windows-only."
}
if (Test-IsAdmin) {
    Fail "Easy-Install refuses to run elevated. Open a normal (non-administrator) PowerShell window and run this script again."
}

if (-not $ParentDir) { $ParentDir = Get-DefaultParentDir }
if (-not $ModelsRoot) {
    $saved = Read-PixaromaConf
    if ($saved.ContainsKey('MODELS_ROOT') -and $saved['MODELS_ROOT']) {
        $ModelsRoot = $saved['MODELS_ROOT']
    } else {
        $ModelsRoot = Get-DefaultModelsRoot
    }
}
$ParentDir = [IO.Path]::GetFullPath($ParentDir)
$ModelsRoot = [IO.Path]::GetFullPath($ModelsRoot)
$installDir = Join-Path $ParentDir 'ComfyUI-Easy-Install'

Write-Step 'Plan'
Write-Info "install:      $installDir"
Write-Info "models root:  $ModelsRoot"
if ($DryRun) { Write-Info "mode:         dry run (no changes)" }

if (Test-Path -LiteralPath $installDir) {
    Fail "$installDir already exists. Move it away or use a different -ParentDir."
}

if (-not $DryRun) {
    if (-not (Test-Path -LiteralPath $ParentDir)) { New-Item -ItemType Directory -Force -Path $ParentDir | Out-Null }
    New-Item -ItemType Directory -Force -Path $ModelsRoot | Out-Null
    $driveRoot = [IO.Path]::GetPathRoot($ModelsRoot)
    try {
        $free = (Get-PSDrive -Name $driveRoot.Substring(0, 1) -ErrorAction Stop).Free
        Write-Info "free space at models root: $(Format-Bytes $free)"
        if ($free -lt 850GB) {
            Write-Warn2 "the full Pixaroma catalog is 782.61 GB; $(Format-Bytes $free) free may not fit everything"
        }
    } catch { }
}

# ---------------------------------------------------------------- fetch release
Write-Step 'Fetching ComfyUI-Easy-Install'
$release = $null
if (-not $DryRun) {
    $release = Invoke-RestMethod -Uri 'https://api.github.com/repos/Tavris1/ComfyUI-Easy-Install/releases/latest' -Headers @{ 'User-Agent' = 'Pixaroma-Setup' } -TimeoutSec 60
}
$work = Join-Path $ParentDir '.pixaroma-easy-setup'
$archive = Join-Path $work 'ComfyUI-Easy-Install.zip'
if ($release) {
    $asset = $release.assets | Where-Object { $_.name -like 'ComfyUI-Easy-Install*.zip' } | Select-Object -First 1
    if (-not $asset) { Fail "latest release ($($release.tag_name)) has no ComfyUI-Easy-Install zip asset" }
    Write-Info "release: $($release.tag_name), asset: $($asset.name) ($(Format-Bytes $asset.size))"
    Download-File -Url $asset.browser_download_url -Dest $archive -ExpectedSize $asset.size
} else {
    Write-Info "[dry-run] download the latest ComfyUI-Easy-Install zip"
}

if (-not $DryRun) {
    if (Test-Path -LiteralPath $work) { Remove-Item -LiteralPath $work -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $work | Out-Null
    Expand-ZipSafe -Zip $archive -Dest $work
    $bat = Join-Path $work 'ComfyUI-Easy-Install.bat'
    $helper = Join-Path $work 'Helper-CEI.zip'
    if (-not (Test-Path -LiteralPath $bat)) { Fail "release zip does not contain ComfyUI-Easy-Install.bat" }
    if (-not (Test-Path -LiteralPath $helper)) { Fail "release zip does not contain Helper-CEI.zip" }

    Write-Step 'Running the Easy-Install installer (interactive)'
    Write-Host @'
   Follow the prompts in the Easy-Install console window.
   Do not close that window until it says the install is complete.
   This script will configure the shared model folder when it returns.
'@ -ForegroundColor Yellow
    $proc = Start-Process -FilePath 'cmd.exe' -ArgumentList @('/c', "`"$bat`"") -WorkingDirectory $work -Wait -PassThru
    Write-Info "Easy-Install exited with code $($proc.ExitCode)"

    $produced = Join-Path $work 'ComfyUI-Easy-Install'
    if (-not (Test-Path -LiteralPath (Join-Path $produced 'ComfyUI\main.py'))) {
        Fail "the install did not produce $produced\ComfyUI\main.py. Leave the staging folder in place for inspection: $work"
    }
    Move-Item -LiteralPath $produced -Destination $installDir -Force
    Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue
    Write-Info "installed to $installDir"
} else {
    Write-Info "[dry-run] extract to $work and run ComfyUI-Easy-Install.bat interactively"
    Write-Info "[dry-run] move $work\ComfyUI-Easy-Install -> $installDir"
}

# --------------------------------------------------------------- configuration
$comfyRoot = Join-Path $installDir 'ComfyUI'
if (-not $DryRun -and -not (Test-Path -LiteralPath (Join-Path $comfyRoot 'main.py'))) {
    $candidate = Get-ChildItem -LiteralPath $installDir -Filter main.py -Recurse -Depth 3 -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($candidate) { $comfyRoot = $candidate.DirectoryName }
}
if (-not $SkipConfig) {
    Write-Step 'Configuring the shared model store'
    Initialize-SharedModels -Root $ModelsRoot
    Write-ExtraModelPaths -ComfyRoot $comfyRoot -Root $ModelsRoot
    Write-PixaromaConf -ComfyDir $comfyRoot -Root $ModelsRoot
}

Write-Step 'Summary'
Write-Info "install:  $installDir"
Write-Info "ComfyUI:  $comfyRoot"
Write-Info "models:   $ModelsRoot"
$launcher = Join-Path $installDir 'run_nvidia_gpu.bat'
if (Test-Path -LiteralPath $launcher) {
    Write-Info "launch:   $launcher"
} else {
    Write-Info "launch:   look for run_nvidia_gpu.bat in $installDir"
}
Write-Info "next:     .\setup.ps1 workflows"
Write-Info "          .\setup.ps1 models --episode 6"
